#!/usr/bin/env python3
"""Write `core/src/literal/printable/table.rs` from one UnicodeData.txt.

SPEC section 2 defines the printable set from the General_Category values
of Unicode 16.0.0. This script reads the file `UnicodeData.txt` of that
version, computes the set, and prints the Rust table on standard output.
Run it with the file of Unicode 16.0.0:

    curl -sSO https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
    python3 scripts/printable.py UnicodeData.txt > core/src/literal/printable/table.rs

The file of Unicode 16.0.0 has the SHA-256 written in `SOURCE_SHA256`
below. The script refuses any other file, so that the table always comes
from the version that the SPEC names.
"""

import hashlib
import sys

VERSION = "16.0.0"
SOURCE_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"

# The categories that CPython's `str.isprintable` refuses. A code point
# that the file does not list has the category Cn.
NOT_PRINTABLE = {"Cc", "Cf", "Cs", "Co", "Cn", "Zl", "Zp", "Zs"}
SPACE = 0x20


def categories(text):
    """Map each listed code point to its General_Category."""
    found = {}
    first = None
    for line in text.splitlines():
        fields = line.split(";")
        point, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = point
        elif name.endswith(", Last>"):
            for each in range(first, point + 1):
                found[each] = category
        else:
            found[point] = category
    return found


def ranges(found):
    """The printable code points, as sorted inclusive ranges."""
    out = []
    for point in range(0x110000):
        if point == SPACE or found.get(point, "Cn") not in NOT_PRINTABLE:
            if out and out[-1][1] == point - 1:
                out[-1][1] = point
            else:
                out.append([point, point])
    return out


def main():
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        sys.exit(f"{sys.argv[1]} has SHA-256 {digest}, not the one of Unicode {VERSION}")
    table = ranges(categories(data.decode("utf-8")))
    print("// This file is generated by `scripts/printable.py` from the file")
    print(f"// `UnicodeData.txt` of Unicode {VERSION}, which has the SHA-256")
    print(f"// {SOURCE_SHA256}.")
    print("// Do not edit it. SPEC section 2 defines this set, and the set never changes.")
    print()
    print("/// Every printable character, as sorted, disjoint, inclusive ranges.")
    print(f"pub(super) const RANGES: [(char, char); {len(table)}] = [")
    for first, last in table:
        print(f"    ('\\u{{{first:04x}}}', '\\u{{{last:04x}}}'),")
    print("];")


main()
